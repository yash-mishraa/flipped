export function assembleMasterPhrases(lexicon: Record<string, unknown>): [string, string][] {
  const seen = new Set<string>();
  const list: [string, string][] = [];

  for (const [adj, nouns] of Object.entries(COMPREHENSIVE_COLLOCATIONS)) {
    for (const n of nouns) {
      if (lexicon[adj] && lexicon[n]) {
        const p = `${adj} ${n}`;
        if (!seen.has(p)) {
          seen.add(p);
          list.push([adj, n]);
        }
      }
    }
  }

  for (const [n1, n2] of NOUN_NOUN_LIST) {
    if (lexicon[n1] && lexicon[n2]) {
      const p = `${n1} ${n2}`;
      if (!seen.has(p)) {
        seen.add(p);
        list.push([n1, n2]);
      }
    }
  }

  return list;
}
